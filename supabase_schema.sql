-- Enable UUID extension if needed for future tables
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. Main quiz_questions table storing scraped ROV Academy lessons & quiz options
CREATE TABLE IF NOT EXISTS public.quiz_questions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_key    TEXT NOT NULL UNIQUE,
    category        TEXT NOT NULL CHECK (
                        category IN ('MOBA101', 'แผนที่', 'ไอเทม', 'ตำแหน่ง')
                    ),
    title           TEXT NOT NULL,
    content         TEXT NOT NULL,
    question_text   TEXT NOT NULL,
    options         JSONB NOT NULL DEFAULT '{}'::jsonb,
    correct_option  CHAR(1) NOT NULL CHECK (correct_option IN ('A', 'B', 'C', 'D')),
    explanation     TEXT NOT NULL DEFAULT '',
    source_url      TEXT NOT NULL DEFAULT 'https://academy.rov.in.th',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Performance indexes for random category sampling & upserts
CREATE INDEX IF NOT EXISTS idx_quiz_questions_category
    ON public.quiz_questions (category);

CREATE INDEX IF NOT EXISTS idx_quiz_questions_created_at
    ON public.quiz_questions (created_at DESC);

-- 3. Automatic updated_at trigger function
CREATE OR REPLACE FUNCTION public.set_quiz_questions_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_quiz_questions_updated_at ON public.quiz_questions;
CREATE TRIGGER trg_quiz_questions_updated_at
    BEFORE UPDATE ON public.quiz_questions
    FOR EACH ROW
    EXECUTE FUNCTION public.set_quiz_questions_updated_at();

-- 4. Row Level Security (RLS) configuration
-- Note: Backend using SUPABASE_SERVICE_ROLE_KEY bypasses RLS automatically.
-- These policies allow safe read access if using the anon key and authenticated inserts.
ALTER TABLE public.quiz_questions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read quiz_questions" ON public.quiz_questions;
CREATE POLICY "Allow public read quiz_questions"
    ON public.quiz_questions
    FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Allow service write quiz_questions" ON public.quiz_questions;
CREATE POLICY "Allow service write quiz_questions"
    ON public.quiz_questions
    FOR ALL
    USING (auth.role() = 'service_role')
    WITH CHECK (auth.role() = 'service_role');

-- 5. Helper RPC for fast random sampling in PostgreSQL (optional optimization)
CREATE OR REPLACE FUNCTION public.get_random_quiz_question(filter_category TEXT DEFAULT NULL)
RETURNS SETOF public.quiz_questions
LANGUAGE sql
VOLATILE
AS $$
    SELECT *
    FROM public.quiz_questions
    WHERE filter_category IS NULL OR category = filter_category
    ORDER BY RANDOM()
    LIMIT 1;
$$;
